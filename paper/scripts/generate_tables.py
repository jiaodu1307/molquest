#!/usr/bin/env python3
"""Generate LaTeX result tables and reusable numeric macros from derived CSVs."""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path
from typing import Any

PAPER_ROOT = Path(__file__).resolve().parents[1]
DERIVED = PAPER_ROOT / "data" / "derived"
TABLES = PAPER_ROOT / "tables" / "generated"
HEADER = "% AUTO-GENERATED by scripts/generate_tables.py. DO NOT EDIT.\n"


def read_csv(name: str) -> list[dict[str, str]]:
    with (DERIVED / name).open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def fmt(value: Any) -> str:
    return f"{float(value):.2f}"


def key(model: str) -> str:
    return re.sub(r"[^a-z0-9]", "", model.lower())


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + content.rstrip() + "\n", encoding="utf-8")


def main_table(models: list[dict[str, str]], rows: list[dict[str, str]]) -> str:
    by_key = {(row["model"], row["mode"]): row for row in rows}
    metrics = ["accuracy", "validity", "similarity", "rmsce", "formula_conservation"]
    extrema: dict[tuple[str, str], float] = {}
    for mode in ("agent", "baseline"):
        for metric in metrics:
            values = [float(by_key[(model["id"], mode)][metric]) for model in models]
            extrema[(mode, metric)] = min(values) if metric == "rmsce" else max(values)

    def cell(row: dict[str, str], mode: str, metric: str) -> str:
        value = float(row[metric])
        rendered = fmt(value)
        if abs(value - extrema[(mode, metric)]) < 0.00005:
            return rf"\textbf{{{rendered}}}"
        return rendered

    lines = [
        r"\begin{table*}[!t]",
        r"  \centering",
        r"  \begin{threeparttable}",
        r"  \resizebox{\textwidth}{!}{%",
        r"  \begin{tabular}{lcccccccccc}",
        r"    \toprule",
        r"    \textbf{Model} & \multicolumn{2}{c}{\textbf{Accuracy~$\uparrow$}} & \multicolumn{2}{c}{\textbf{Validity~$\uparrow$}} & \multicolumn{2}{c}{\textbf{Similarity~$\uparrow$}} & \multicolumn{2}{c}{\textbf{Calibration~$\downarrow$}} & \multicolumn{2}{c}{\textbf{Formula Cons.~$\uparrow$}}\\",
        r"    \cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7} \cmidrule(lr){8-9} \cmidrule(lr){10-11}",
        r"    & \textbf{Agent} & \textbf{Base} & \textbf{Agent} & \textbf{Base} & \textbf{Agent} & \textbf{Base} & \textbf{Agent} & \textbf{Base} & \textbf{Agent} & \textbf{Base}\\",
        r"    \midrule",
    ]
    for model in models:
        agent = by_key[(model["id"], "agent")]
        baseline = by_key[(model["id"], "baseline")]
        values: list[str] = []
        for metric in metrics:
            values.extend([cell(agent, "agent", metric), cell(baseline, "baseline", metric)])
        lines.append(f"    {model['latex']:<30} & " + " & ".join(values) + r"\\")
    lines.extend(
        [
            r"    \bottomrule",
            r"  \end{tabular}}",
            r"  \begin{tablenotes}\scriptsize",
            r"    \item[$\dagger$] Models with dedicated ``Thinking'' mode enabled.",
            r"    \item[$\ddagger$] Reasoning via parameter: extended thinking (Claude) / reasoning effort (GPT).",
            r"    \item Formula conservation is conditioned on RDKit-valid predictions; all other denominators are stated in Section~\ref{sec:evaluation-metrics}.",
            r"  \end{tablenotes}",
            r"  \end{threeparttable}",
            r"  \caption{Main results on MolQuest under the Agent and Baseline settings.}",
            r"  \label{tab:main-results}",
            r"\end{table*}",
        ]
    )
    return "\n".join(lines)


def stereo_table(models: list[dict[str, str]], rows: list[dict[str, str]]) -> str:
    by_key = {(row["model"], row["mode"]): row for row in rows}
    lines = [
        r"\begin{table}[htbp]", r"  \centering", r"  \small", r"  \begin{tabular}{lcc}",
        r"    \toprule", r"    \textbf{Model} & \textbf{Agent} & \textbf{Baseline} \\", r"    \midrule",
    ]
    for model in models:
        agent = by_key[(model["id"], "agent")]
        baseline = by_key[(model["id"], "baseline")]
        lines.append(f"    {model['name']:<27} & {fmt(agent['stereo_agnostic_accuracy'])} & {fmt(baseline['stereo_agnostic_accuracy'])} \\\\")
    lines.extend(
        [r"    \bottomrule", r"  \end{tabular}", r"  \caption{Stereochemistry-agnostic accuracy (\%) on the common \PaperMetric{datasetcompounds} cases.}", r"  \label{tab:stereo-agnostic-full}", r"\end{table}"]
    )
    return "\n".join(lines)


def run_table(models: list[dict[str, str]], rows: list[dict[str, str]]) -> str:
    by_model = {row["model"]: row for row in rows}
    lines = [
        r"\begin{table*}[htbp]", r"  \centering", r"  \small", r"  \begin{tabular}{lcccc}",
        r"    \toprule", r"    \textbf{Model} & \textbf{Avg. LLM} & \textbf{Avg. Planner} & \textbf{LLM (Correct)} & \textbf{LLM (Wrong)} \\", r"    \midrule",
    ]
    for model in models:
        row = by_model[model["id"]]
        lines.append(
            f"    {model['name']:<27} & {fmt(row['avg_llm_calls'])} & {fmt(row['avg_planner_calls'])} & "
            f"{fmt(row['avg_llm_calls_correct'])} & {fmt(row['avg_llm_calls_wrong'])} \\\\"
        )
    lines.extend(
        [r"    \bottomrule", r"  \end{tabular}", r"  \caption{Run-level process diagnostics on the common \PaperMetric{datasetcompounds} cases.}", r"  \label{tab:run-level-full}", r"\end{table*}"]
    )
    return "\n".join(lines)


def trace_table(models: list[dict[str, str]], rows: list[dict[str, str]], *, representative: bool) -> str:
    by_model = {row["model"]: row for row in rows}
    if representative:
        ids = ["gemini-3-flash", "claude-sonnet-4.5", "deepseek-v3.2-thinking", "qwen3-max", "deepseek-v3.1"]
    else:
        ids = [model["id"] for model in models if model["id"] in by_model]
    names = {model["id"]: model["name"] for model in models}
    columns = "lccccc" if representative else "lcccccc"
    lines = [r"\begin{table*}[!t]" if representative else r"\begin{table*}[htbp]", r"  \centering", r"  \small", rf"  \begin{{tabular}}{{{columns}}}", r"    \toprule"]
    if representative:
        lines.append(r"    \textbf{Model} & \textbf{Acc.} & \textbf{Avg. Calls} & \textbf{Acc./Call} & \textbf{Repeated (\%)} & \textbf{Unavailable (\%)} \\")
    else:
        lines.append(r"    \textbf{Model} & \textbf{Acc.} & \textbf{Rounds} & \textbf{Calls} & \textbf{Acc./Call} & \textbf{Repeated (\%)} & \textbf{Unavailable (\%)} \\")
    lines.append(r"    \midrule")
    for model_id in ids:
        row = by_model[model_id]
        efficiency = float(row["accuracy"]) / float(row["avg_tool_calls"])
        if representative:
            values = [row["accuracy"], row["avg_tool_calls"], efficiency, row["repeated_tool_call_rate"], row["unavailable_tool_call_rate"]]
        else:
            values = [row["accuracy"], row["avg_rounds"], row["avg_tool_calls"], efficiency, row["repeated_tool_call_rate"], row["unavailable_tool_call_rate"]]
        lines.append(f"    {names[model_id]:<27} & " + " & ".join(fmt(v) for v in values) + r" \\")
    caption = "Representative trace-level process diagnostics. Rates are percentages of all tool calls." if representative else r"Trace-level process diagnostics on the common \PaperMetric{datasetcompounds} cases."
    label = "tab:process-diagnostics" if representative else "tab:trace-level-full"
    lines.extend([r"    \bottomrule", r"  \end{tabular}", f"  \\caption{{{caption}}}", f"  \\label{{{label}}}", r"\end{table*}"])
    return "\n".join(lines)


def dataset_audit_table(rows: list[dict[str, str]]) -> str:
    lines = [
        r"\begin{table}[!t]",
        r"  \centering",
        r"  \small",
        r"  \begin{tabular}{lr}",
        r"    \toprule",
        r"    \textbf{Dataset audit item} & \textbf{Coverage} \\",
        r"    \midrule",
    ]
    for row in rows:
        coverage = row["count"]
        if row["show_denominator"].lower() == "true":
            coverage = f"{row['count']} / {row['total']}"
        lines.append(f"    {row['label']} & {coverage} \\\\")
    lines.extend(
        [
            r"    \bottomrule",
            r"  \end{tabular}",
            r"  \caption{Compact audit of the expert-validated MolQuest dataset.}",
            r"  \label{tab:dataset-audit}",
            r"\end{table}",
        ]
    )
    return "\n".join(lines)


def metric_macros(
    models: list[dict[str, str]],
    main_rows: list[dict[str, str]],
    stereo_rows: list[dict[str, str]],
    run_rows: list[dict[str, str]],
    dataset_rows: list[dict[str, str]],
    rmsce_bins: int,
) -> str:
    by_key = {(row["model"], row["mode"]): row for row in main_rows}
    lines = [r"\newcommand{\PaperMetric}[1]{\csname mqmetric@#1\endcsname}"]
    for model in models:
        model_key = key(model["id"])
        for mode in ("agent", "baseline"):
            row = by_key[(model["id"], mode)]
            for metric in ("accuracy", "validity", "similarity", "rmsce", "formula_conservation"):
                macro_key = f"{model_key}{mode}{key(metric)}"
                lines.append(rf"\expandafter\def\csname mqmetric@{macro_key}\endcsname{{{fmt(row[metric])}}}")
        delta = float(by_key[(model["id"], "agent")]["accuracy"]) - float(by_key[(model["id"], "baseline")]["accuracy"])
        lines.append(rf"\expandafter\def\csname mqmetric@{model_key}accuracydelta\endcsname{{{delta:+.2f}}}")
    for row in stereo_rows:
        macro_key = f"{key(row['model'])}{row['mode']}stereoagnosticaccuracy"
        lines.append(rf"\expandafter\def\csname mqmetric@{macro_key}\endcsname{{{fmt(row['stereo_agnostic_accuracy'])}}}")
    for row in run_rows:
        model_key = key(row["model"])
        for metric in ("avg_llm_calls", "avg_planner_calls", "avg_llm_calls_correct", "avg_llm_calls_wrong"):
            macro_key = f"{model_key}{key(metric)}"
            lines.append(rf"\expandafter\def\csname mqmetric@{macro_key}\endcsname{{{fmt(row[metric])}}}")
    agent_deltas = []
    baseline_deltas = []
    for row in stereo_rows:
        delta = float(row["stereo_agnostic_accuracy"]) - float(row["strict_accuracy"])
        (agent_deltas if row["mode"] == "agent" else baseline_deltas).append(delta)
    lines.append(rf"\expandafter\def\csname mqmetric@meanagentstereodelta\endcsname{{{sum(agent_deltas) / len(agent_deltas):.2f}}}")
    lines.append(rf"\expandafter\def\csname mqmetric@meanbaselinestereodelta\endcsname{{{sum(baseline_deltas) / len(baseline_deltas):.2f}}}")
    lines.append(rf"\expandafter\def\csname mqmetric@modelvariantcount\endcsname{{{len(models)}}}")
    lines.append(rf"\expandafter\def\csname mqmetric@modelsettingconfigurationcount\endcsname{{{len(models) * 2}}}")
    lines.append(rf"\expandafter\def\csname mqmetric@rmscebins\endcsname{{{rmsce_bins}}}")
    for row in dataset_rows:
        lines.append(rf"\expandafter\def\csname mqmetric@dataset{row['key']}\endcsname{{{row['count']}}}")
        lines.append(rf"\expandafter\def\csname mqmetric@dataset{row['key']}total\endcsname{{{row['total']}}}")
    return "\n".join(lines)


def main() -> None:
    models = json.loads((PAPER_ROOT / "config" / "models.json").read_text(encoding="utf-8"))
    protocol = json.loads((PAPER_ROOT / "config" / "metric_protocol.json").read_text(encoding="utf-8"))
    main_rows = read_csv("main_results.csv")
    stereo_rows = read_csv("stereo_results.csv")
    run_rows = read_csv("run_metrics.csv")
    trace_rows = read_csv("trace_metrics.csv")
    dataset_rows = read_csv("dataset_audit.csv")
    write(TABLES / "main_results.tex", main_table(models, main_rows))
    write(TABLES / "dataset_audit.tex", dataset_audit_table(dataset_rows))
    write(TABLES / "stereo_results.tex", stereo_table(models, stereo_rows))
    write(TABLES / "run_metrics.tex", run_table(models, run_rows))
    write(TABLES / "trace_metrics.tex", trace_table(models, trace_rows, representative=False))
    write(TABLES / "representative_trace_metrics.tex", trace_table(models, trace_rows, representative=True))
    write(
        PAPER_ROOT / "generated" / "metric_macros.tex",
        metric_macros(models, main_rows, stereo_rows, run_rows, dataset_rows, int(protocol["rmsce"]["bins"])),
    )
    print("Generated six LaTeX tables and generated/metric_macros.tex")


if __name__ == "__main__":
    main()
